-- =====================================================================
--  Fursa — Database schema (PostgreSQL)
--  Matches ERD v5: 20 tables. Column names follow the match scoring algorithm.
--  Safe to re-run: it drops the old tables first (ALL DATA IS DELETED).
-- =====================================================================

DROP TABLE IF EXISTS
  payments, notifications, cv_suggestions, cv_reviews, interviews, related_fields,
  application_history, applications, match_scores, job_skills, seeker_skills,
  jobs, subscriptions, resumes, password_resets, companies, seeker_profiles,
  plans, skills, users
CASCADE;

-- ---------------------------------------------------------------------
-- 1. Accounts and job seekers
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name    VARCHAR(50)  NOT NULL,
  last_name     VARCHAR(50)  NOT NULL,
  email         VARCHAR(255) NOT NULL UNIQUE,
  password_hash TEXT         NOT NULL,
  role          VARCHAR(10)  NOT NULL CHECK (role IN ('seeker','employer','admin')),
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE password_resets (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash  TEXT        NOT NULL,
  expires_at  TIMESTAMPTZ NOT NULL,
  used_at     TIMESTAMPTZ
);

-- One-to-one with users: user_id is both PK and FK
CREATE TABLE seeker_profiles (
  user_id           INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  phone             VARCHAR(20),
  major             VARCHAR(100) NOT NULL,
  graduation_status VARCHAR(30)  NOT NULL,
  years_experience  NUMERIC(3,1) CHECK (years_experience >= 0),  -- NULL = unknown (experience excluded from score)
  -- Optional multi-select preferences. Empty list {} = no preference (neutral score).
  job_types  TEXT[] NOT NULL DEFAULT '{}'
    CHECK (job_types  <@ ARRAY['internship','full_time','part_time']::TEXT[]),
  work_modes TEXT[] NOT NULL DEFAULT '{}'
    CHECK (work_modes <@ ARRAY['onsite','remote','hybrid']::TEXT[])
  -- cv_embedding vector(1536) is added at the end of this file (needs the vector extension)
);

CREATE TABLE resumes (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seeker_id         INTEGER NOT NULL REFERENCES seeker_profiles(user_id) ON DELETE CASCADE,
  file_name         VARCHAR(255) NOT NULL,
  file_url          TEXT         NOT NULL,
  parsed_text       TEXT,
  parsed_experience TEXT,
  parsed_languages  TEXT,
  is_current        BOOLEAN      NOT NULL DEFAULT true,
  uploaded_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- A seeker can have only ONE current CV (old ones stay for past applications)
CREATE UNIQUE INDEX one_current_resume ON resumes(seeker_id) WHERE is_current;

-- ---------------------------------------------------------------------
-- 2. Skills
-- ---------------------------------------------------------------------
CREATE TABLE skills (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(60) NOT NULL UNIQUE
);

-- "React" and "react" are the same skill
CREATE UNIQUE INDEX skills_name_lower_key ON skills (lower(trim(name)));

CREATE TABLE seeker_skills (
  seeker_id INTEGER NOT NULL REFERENCES seeker_profiles(user_id) ON DELETE CASCADE,
  skill_id  INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
  PRIMARY KEY (seeker_id, skill_id)
);

-- ---------------------------------------------------------------------
-- 3. Employer
-- ---------------------------------------------------------------------
CREATE TABLE companies (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id   INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,  
  name      VARCHAR(150) NOT NULL,
  logo_url  TEXT,
  website   VARCHAR(255),
  industry  VARCHAR(100) NOT NULL,
  location  VARCHAR(100) NOT NULL,
  phone     VARCHAR(20),
  about     TEXT,
  -- Commercial Registration (CR) number the admin checks before the company can publish jobs
  cr_number VARCHAR(20),
  -- pending = waiting for the admin (can sign in, edit the profile and save drafts, not publish)
  status    VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  rejection_reason TEXT,             -- the admin's last reason (kept when the company sends again, so the admin sees it)
  reviewed_at      TIMESTAMPTZ,
  -- a rejected company can fix its details and send them again: back to 'pending' with a note for the admin
  review_note      TEXT,
  resubmitted_at   TIMESTAMPTZ
);

CREATE TABLE plans (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name               VARCHAR(30)  NOT NULL UNIQUE,
  price_bhd_month    NUMERIC(8,3) NOT NULL DEFAULT 0,      
  max_active_jobs    INTEGER,                              
  has_ai_ranking     BOOLEAN NOT NULL DEFAULT false,
  has_match_reasons  BOOLEAN NOT NULL DEFAULT false,
  has_bulk_actions   BOOLEAN NOT NULL DEFAULT false,
  has_hiring_summary BOOLEAN NOT NULL DEFAULT false
);

-- The paid plan a company picked at sign up. It starts on Free and pays for this plan
-- after the admin approves it (NULL = picked Free, or already paid)
ALTER TABLE companies ADD COLUMN requested_plan_id INTEGER REFERENCES plans(id);

CREATE TABLE subscriptions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  INTEGER NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  plan_id     INTEGER NOT NULL REFERENCES plans(id),
  status      VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active','cancelled','expired')),
  started_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  renews_at   TIMESTAMPTZ
);
-- Two companies can't share a name ("PearlSoft" = " pearlsoft ")
CREATE UNIQUE INDEX companies_name_key ON companies (lower(trim(name)));

-- A company can have only ONE active subscription at a time
CREATE UNIQUE INDEX one_active_subscription ON subscriptions(company_id) WHERE status = 'active';

CREATE TABLE jobs (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id       INTEGER NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  job_type         VARCHAR(10)  CHECK (job_type IN ('internship','full_time','part_time')),
  work_mode        VARCHAR(10)  CHECK (work_mode IN ('onsite','remote','hybrid')),
  title            VARCHAR(150) NOT NULL,
  description      TEXT ,
  responsibilities TEXT,
  location         VARCHAR(100) ,                 
  salary           NUMERIC(8,3),                          
  deadline         DATE ,
  field            VARCHAR(100),                          
  major_must_have  BOOLEAN NOT NULL DEFAULT false,
  min_years        SMALLINT NOT NULL DEFAULT 0,
  max_years        SMALLINT,
  language         TEXT,                                  
  status           VARCHAR(10) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','open','closed')),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (max_years IS NULL OR max_years >= min_years),
  CHECK (status = 'draft' OR (job_type IS NOT NULL AND work_mode IS NOT NULL AND description IS NOT NULL AND location IS NOT NULL AND deadline IS NOT NULL))
);

CREATE TABLE job_skills (
  job_id       INTEGER NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  skill_id     INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
  is_required  BOOLEAN NOT NULL DEFAULT false,      -- "Must-have" on the Post a job page
  PRIMARY KEY (job_id, skill_id)
);

-- Majors/fields that count as related for the Education score (0.5).
-- Store each pair ONCE; the scoring code checks both directions.
CREATE TABLE related_fields (
  field_a VARCHAR(100) NOT NULL,
  field_b VARCHAR(100) NOT NULL,
  PRIMARY KEY (field_a, field_b),
  CHECK (field_a <> field_b)
);

-- ---------------------------------------------------------------------
-- 4. Matching and hiring
-- ---------------------------------------------------------------------
CREATE TABLE match_scores (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id       INTEGER  NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  seeker_id    INTEGER  NOT NULL REFERENCES seeker_profiles(user_id) ON DELETE CASCADE,
  score        SMALLINT NOT NULL CHECK (score BETWEEN 0 AND 100),
  tier         VARCHAR(10) NOT NULL CHECK (tier IN ('strong','good','low')),  -- 80+ / 60-79 / 0-59
  is_qualified BOOLEAN  NOT NULL DEFAULT true,  -- false if a required skill / must-have major is missing (Not qualified tab)
  breakdown    JSONB    NOT NULL DEFAULT '{}',  -- component values, e.g. {"skills":0.625,"cv":0.7,...}
  computed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (job_id, seeker_id)                    -- used by the upsert
);

CREATE TABLE applications (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id           INTEGER NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  seeker_id        INTEGER NOT NULL REFERENCES seeker_profiles(user_id) ON DELETE CASCADE,
  resume_id        INTEGER NOT NULL REFERENCES resumes(id),     -- the CV actually sent
  status           VARCHAR(12) NOT NULL DEFAULT 'applied'
                   CHECK (status IN ('applied','shortlisted','interview','accepted','rejected')),
  rejection_reason TEXT,
  applied_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (job_id, seeker_id)
);

CREATE TABLE application_history (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INTEGER NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  changed_by     INTEGER REFERENCES users(id) ON DELETE SET NULL,
  from_status    VARCHAR(12),                              -- NULL for the first "applied" row
  to_status      VARCHAR(12) NOT NULL
                 CHECK (to_status IN ('applied','shortlisted','interview','accepted','rejected')),
  changed_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE interviews (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id    INTEGER NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  scheduled_at      TIMESTAMPTZ NOT NULL,
  type              VARCHAR(10) NOT NULL CHECK (type IN ('in_person','online')),
  location_or_link  TEXT NOT NULL,
  note_to_applicant TEXT,
  employer_notes    TEXT,
  status            VARCHAR(25) NOT NULL DEFAULT 'invited'
                    CHECK (status IN ('invited','confirmed','reschedule_requested','done'))
);

-- ---------------------------------------------------------------------
-- 5. AI CV Optimizer
-- ---------------------------------------------------------------------
CREATE TABLE cv_reviews (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id       INTEGER  NOT NULL REFERENCES resumes(id) ON DELETE CASCADE,
  strength_score  SMALLINT NOT NULL CHECK (strength_score BETWEEN 0 AND 100),
  potential_score SMALLINT CHECK (potential_score BETWEEN 0 AND 100),
  is_advanced     BOOLEAN  NOT NULL DEFAULT false,
  comparison      JSONB,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cv_suggestions (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id       INTEGER NOT NULL REFERENCES cv_reviews(id) ON DELETE CASCADE,
  section         VARCHAR(20) NOT NULL CHECK (section IN ('summary','projects','skills','education','layout')),
  before_text     TEXT NOT NULL,
  after_text      TEXT NOT NULL,
  reason          TEXT,
  points          SMALLINT NOT NULL DEFAULT 0,
  is_free_preview BOOLEAN  NOT NULL DEFAULT false,
  status          VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','dismissed'))
);

-- ---------------------------------------------------------------------
-- 6. Notifications and payments
-- ---------------------------------------------------------------------
CREATE TABLE notifications (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  application_id INTEGER REFERENCES applications(id) ON DELETE CASCADE,  
  job_id         INTEGER REFERENCES jobs(id) ON DELETE CASCADE,          
  type           VARCHAR(15) NOT NULL
                 CHECK (type IN ('interview','new_matches','rejected','accepted','cv_ready','deadline', 'shortlisted', 'new_applicants','interview_reply','job_closed','plan','account')),
  title          VARCHAR(150) NOT NULL,
  message        TEXT NOT NULL,
  is_read        BOOLEAN NOT NULL DEFAULT false,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Card number / CVV are NEVER stored.
CREATE TABLE payments (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INTEGER NOT NULL REFERENCES users(id),
  subscription_id INTEGER REFERENCES subscriptions(id),   -- filled for plan payments
  cv_review_id    INTEGER REFERENCES cv_reviews(id),      -- filled for CV report payments
  item            VARCHAR(20) NOT NULL CHECK (item IN ('plan','advanced_cv_report')),
  method          VARCHAR(12) NOT NULL CHECK (method IN ('card','benefitpay')),
  subtotal_bhd    NUMERIC(8,3) NOT NULL,
  vat_bhd         NUMERIC(8,3) NOT NULL,
  total_bhd       NUMERIC(8,3) NOT NULL,
  status          VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','paid','failed')),
  is_simulated    BOOLEAN NOT NULL DEFAULT true,
  paid_at         TIMESTAMPTZ,
  -- the right link must be filled for each item
  CHECK ( (item = 'plan' AND subscription_id IS NOT NULL AND cv_review_id IS NULL)
       OR (item = 'advanced_cv_report' AND cv_review_id IS NOT NULL AND subscription_id IS NULL) ),
  CHECK (total_bhd = subtotal_bhd + vat_bhd)
);

-- ---------------------------------------------------------------------
-- 7. Indexes on the foreign keys we search by most (makes pages fast)
-- ---------------------------------------------------------------------
CREATE INDEX idx_jobs_company          ON jobs(company_id);
CREATE INDEX idx_jobs_status           ON jobs(status);
CREATE INDEX idx_applications_job      ON applications(job_id);
CREATE INDEX idx_applications_seeker   ON applications(seeker_id);
CREATE INDEX idx_match_scores_job      ON match_scores(job_id, score DESC);
CREATE INDEX idx_match_scores_seeker   ON match_scores(seeker_id, score DESC);
CREATE INDEX idx_history_application   ON application_history(application_id);
CREATE INDEX idx_interviews_application ON interviews(application_id);
CREATE INDEX idx_resumes_seeker        ON resumes(seeker_id);
CREATE INDEX idx_notifications_user    ON notifications(user_id, is_read);
CREATE INDEX idx_payments_user         ON payments(user_id);
CREATE INDEX idx_job_skills_skill      ON job_skills(skill_id);
CREATE INDEX idx_seeker_skills_skill   ON seeker_skills(skill_id);
CREATE INDEX idx_jobs_type_mode        ON jobs(job_type, work_mode);

-- ---------------------------------------------------------------------
-- 8. AI embeddings (pgvector) for CV similarity
--    Supabase has the "vector" extension. A normal Windows PostgreSQL install
--    usually does NOT, so locally these two columns are skipped with a notice.
--    Everything else works the same; the CV component is simply excluded.
-- ---------------------------------------------------------------------
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'vector') THEN
    CREATE EXTENSION IF NOT EXISTS vector;
    ALTER TABLE seeker_profiles ADD COLUMN IF NOT EXISTS cv_embedding vector(1536);
    ALTER TABLE jobs            ADD COLUMN IF NOT EXISTS jd_embedding vector(1536);
    RAISE NOTICE 'vector extension found: cv_embedding and jd_embedding added';
  ELSE
    RAISE NOTICE 'vector extension not installed: embedding columns skipped (OK for local testing)';
  END IF;
END $$;
